"""형식 있는 개인정보의 정규식 (M2 가명화의 출발점). 지금은 요청 로그의 안전장치(#11)가 쓴다.

- 측정용 사본(bench/run_judges.py의 PATTERNS)에서 시작해 고쳤다. 지난 측정 결과를 다시 낼 수 있도록
  측정용 사본은 그대로 두고, 게이트웨이는 이 파일을 고쳐 나간다
- 이름은 정규식으로 잡지 않는다. 사용자 사전(M2)과 로컬 판단(남은 개인정보)의 몫이다

정규식을 고칠 때 지킬 것 (11/01 보안 검토)
- **반복에는 길이 상한을 둔다.** 측정용 사본의 주소·이메일 패턴(`\\S+…`, `[\\w.]+@`)은 공백 없는 긴 입력
  수천 자에서 끝나지 않았다. 긴 문서도 가명화한다(D19)고 했으니 입력 하나로 게이트웨이가 멈출 수 있었다
- **재현율을 먼저 한다.** 가명화의 오탐은 복원 단계에서 되돌아오지만, 미탐은 원본이 그대로 밖으로 나간다.
  주소 패턴은 보안 검토를 세 번 거치며 정했다:
  1. 끝 글자(시·구·로)를 구간에 못 담게 함 → "구로구", "가로수길", 두 칸 띄어쓰기를 놓침
  2. 어절 단위로 맞춤 → 띄어쓰기 없는 주소("서울시마포구가상로123")와 긴 말 뒤에 붙은 주소를 놓침
  3. 지금: 한글 1~6자의 짧은 게으른 구간 + 공백 0~3칸. 위 경우를 모두 잡고 시간은 길이에 비례한다.
     대가로 "내년도 연구개발비로 30억" 오탐은 받아들인다
  시·도 없이 구부터 쓴 주소("마포구 가상로 123")는 "요구 사항으로 3개" 같은 문장과 구분되지 않아 못 잡는다(M2)
- **숫자 경계를 둔다** (`(?<!\\d)`, `(?!\\d)`). 주문번호 같은 긴 숫자의 일부를 개인정보로 잡지 않는다
- 하이픈 없는 휴대전화·주민번호·카드번호도 잡는다. 하이픈 없는 주민번호는 생년월일·성별 자리가 맞을 때만
  잡아 `2026110300123` 같은 주문번호와 구분한다. 하이픈 없는 계좌번호는 다른 번호와 구분할 수 없어 못 잡는다
"""
import re
import sys
import unicodedata

def _normalize_table() -> dict[int, str | None]:
    """가리기 전에 바꿀 문자표. 시작할 때 한 번 만든다 (유니코드 전체를 훑는 데 0.2초 안팎)."""
    table: dict[int, str | None] = {0xFF01 + i: chr(0x21 + i) for i in range(94)}   # 전각 영숫자·기호 → 반각
    for cp in range(sys.maxunicode + 1):
        cat = unicodedata.category(chr(cp))
        if cat == "Cf":                       # 보이지 않는 서식 문자: 폭 0 공백, 소프트 하이픈, BOM, 방향 표시 …
            table[cp] = None
        elif cat == "Pd":                     # 모든 대시: 엔대시·엠대시·물결 대시 …
            table[cp] = "-"
        elif cat == "Zs" and cp != 0x20:      # 모든 공백 문자: 전각 공백, 줄바꿈 없는 공백 …
            table[cp] = " "
    for cp in (*range(0xFE00, 0xFE10), *range(0xE0100, 0xE01F0)):   # 이체 선택자 (글자 모양만 바꾼다)
        table[cp] = None
    table[0x2212] = "-"                       # 빼기 기호 (수학 기호라 Pd가 아니다)
    return table


_NORMALIZE = _normalize_table()


def normalize_text(text: str) -> str:
    """가리기 전에 표기를 맞춘다 (#44 보안 검토: 같은 값이 다른 표기로 들어와 사전·정규식을 피하는 것을 막는다).
    - 유니코드 NFC: 자모를 나눠 쓴 "김민수"(NFD)를 한 글자씩 합친다
    - 보이지 않는 서식 문자·이체 선택자를 지운다: "김​민수"는 화면에는 김민수로 보인다
    - 전각 → 반각, 모든 대시 → 하이픈, 모든 공백 문자 → 공백: "０１０–１２３４" → "010-1234"
    NFKC는 쓰지 않는다. "ㅋㅋ"·"ㅠㅠ" 같은 한글 낱자를 조합용 자모로 바꿔 버린다.
    NFKC로만 풀리는 표기(동그라미 숫자 등)는 masker의 마지막 검사(unmasked)가 막는다."""
    return unicodedata.normalize("NFC", text.translate(_NORMALIZE)).translate(_NORMALIZE)


def find_pii_compat(text: str) -> list[str]:
    """NFKC로 바꾼 사본에서 찾는다. 가린 뒤의 문장에 이것이 걸리면, normalize_text로도 못 맞춘 표기
    (동그라미 숫자 "⓪①⓪", 위첨자 숫자 등)로 쓴 개인정보가 남은 것이다. 사본은 검사에만 쓰고 밖으로 보내지 않는다."""
    return find_pii(unicodedata.normalize("NFKC", text))


_ROAD = r"[가-힣\d]{1,12}?(?:로|길)\s{0,3}\d{1,5}(?:-\d{1,5})?(?:,?\s{0,3}\d{1,4}동\s{0,3}\d{1,5}호)?"
_BIG_SIDO = "서울|부산|대구|인천|광주|대전|울산|세종|제주"   # 구·군 없이 쓰는 주소도 주소로 볼 시·도

# 긴 패턴부터 본다. 주민번호(6-7자리)가 계좌번호 패턴에 먼저 잡히지 않게 한다
PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    ("주민번호", re.compile(r"(?<!\d)(?:\d{6}-\d{7}"
                            r"|\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])[1-8]\d{6})(?!\d)")),
    ("카드번호", re.compile(r"(?<!\d)\d{4}([-. ]?)\d{4}\1\d{4}\1\d{4}(?!\d)")),
    ("전화번호", re.compile(r"(?<!\d)(?:0\d{1,2}-\d{3,4}-\d{4}|01[016789]([. ]?)\d{3,4}\1\d{4})(?!\d)")),
    ("이메일", re.compile(r"[\w.+-]{1,64}@[\w-]{1,63}(?:\.[\w-]{1,63}){1,4}")),
    ("계좌번호", re.compile(r"(?<!\d)\d{2,6}-\d{2,6}-\d{2,6}(?:-\d{1,6})?(?!\d)")),
    # 주소: (도) 시·도 → 구·군 → 로·길 + 번호, 또는 큰 시·도 이름 → 로·길 + 번호 (구 없는 주소)
    # 각 구간은 한글 1~6자의 짧은 게으른 반복이라 시작 위치마다 시도하는 조합이 몇십 개로 묶인다 (과부하 없음).
    # 띄어쓰기가 없거나("서울시마포구가상로123") 긴 말 뒤에 붙어도 잡는다. "구로구"·"가로수길"도 된다
    ("주소", re.compile(rf"(?:[가-힣]{{1,7}}?[시도]\s{{0,3}})?[가-힣]{{1,6}}?[시도]\s{{0,3}}[가-힣]{{1,5}}?[구군]\s{{0,3}}{_ROAD}"
                        rf"|(?:{_BIG_SIDO})[가-힣]{{0,5}}?[시도]\s{{0,3}}{_ROAD}")),
]
# 2026-11-03은 계좌번호 모양이지만 날짜다. 실제 월·일만 날짜로 본다
_DATE = re.compile(r"(?:19|20)\d{2}-(?:0?[1-9]|1[0-2])-(?:0?[1-9]|[12]\d|3[01])")


def is_date(kind: str, value: str) -> bool:
    """계좌번호 패턴에 걸렸지만 실제로는 날짜인 값 (가명화하지 않는다)."""
    return kind == "계좌번호" and _DATE.fullmatch(value) is not None


def find_pii(text: str) -> list[str]:
    """형식 있는 개인정보 값의 종류를 찾은 순서대로 돌려준다(같은 종류가 여러 번이면 여러 번).
    찾은 값은 지우고 다음 패턴을 봐서, 주민번호 하나가 계좌번호로 한 번 더 세지지 않는다."""
    found = []
    for kind, pattern in PATTERNS:
        for m in pattern.finditer(text):
            if is_date(kind, m.group()):
                continue
            found.append(kind)
            text = text.replace(m.group(), " ")
    return found
