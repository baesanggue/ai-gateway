"""형식 있는 개인정보의 정규식 (M2 가명화의 출발점). 지금은 요청 로그의 안전장치(#11)가 쓴다.

- 측정용 사본(bench/run_judges.py의 PATTERNS)에서 시작해 고쳤다. 지난 측정 결과를 다시 낼 수 있도록
  측정용 사본은 그대로 두고, 게이트웨이는 이 파일을 고쳐 나간다
- 이름은 정규식으로 잡지 않는다. 사용자 사전(M2)과 로컬 판단(남은 개인정보)의 몫이다

정규식을 고칠 때 지킬 것 (11/01 보안 검토)
- **반복에는 길이 상한을 둔다.** 측정용 사본의 주소·이메일 패턴(`\\S+…`, `[\\w.]+@`)은 공백 없는 긴 입력
  수천 자에서 끝나지 않았다. 긴 문서도 가명화한다(D19)고 했으니 입력 하나로 게이트웨이가 멈출 수 있었다
- **주소는 어절 단위로 맞춘다.** 처음 고칠 때 구간이 끝 글자(시·구·로)를 아예 못 담게 했더니 "구로구",
  "가로수길", 두 칸 띄어쓰기를 놓쳤다(두 번째 보안 검토). 어절 끝 글자 + 공백으로 나누면 이름 안의 글자는
  괜찮고 나누는 방법도 하나뿐이다. 측정용 사본이 걸리던 "내년도 연구개발비로 30억" 오탐도 없어졌다.
  구·군이 없는 주소("세종시 한누리대로 2130")는 못 잡는다. 시·도 이름 목록과 함께 M2에서 다룬다
- **숫자 경계를 둔다** (`(?<!\\d)`, `(?!\\d)`). 주문번호 같은 긴 숫자의 일부를 개인정보로 잡지 않는다
- 하이픈 없는 휴대전화·주민번호·카드번호도 잡는다. 하이픈 없는 주민번호는 생년월일·성별 자리가 맞을 때만
  잡아 `2026110300123` 같은 주문번호와 구분한다. 하이픈 없는 계좌번호는 다른 번호와 구분할 수 없어 못 잡는다
"""
import re

# 긴 패턴부터 본다. 주민번호(6-7자리)가 계좌번호 패턴에 먼저 잡히지 않게 한다
PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    ("주민번호", re.compile(r"(?<!\d)(?:\d{6}-\d{7}"
                            r"|\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])[1-8]\d{6})(?!\d)")),
    ("카드번호", re.compile(r"(?<!\d)\d{4}([-. ]?)\d{4}\1\d{4}\1\d{4}(?!\d)")),
    ("전화번호", re.compile(r"(?<!\d)(?:0\d{1,2}-\d{3,4}-\d{4}|01[016789]([. ]?)\d{3,4}\1\d{4})(?!\d)")),
    ("이메일", re.compile(r"[\w.+-]{1,64}@[\w-]{1,63}(?:\.[\w-]{1,63}){1,4}")),
    ("계좌번호", re.compile(r"(?<!\d)\d{2,6}-\d{2,6}-\d{2,6}(?:-\d{1,6})?(?!\d)")),
    # 주소는 어절 단위로 맞춘다: (도) 시 → 구·군 → 로·길 + 번호. 각 어절은 끝 글자가 시·도 / 구·군 / 로·길이고
    # 바로 뒤가 공백이라 나누는 방법이 하나뿐이다. 그래서 "구로구", "가로수길"처럼 이름 안에 끝 글자가 있어도 된다
    ("주소", re.compile(r"(?<!\S)(?:\S{1,10}[시도]\s{1,3})?\S{1,10}[시도]\s{1,3}\S{1,10}[구군]\s{1,3}"
                        r"\S{1,15}(?:로|길)\s{0,3}\d{1,5}(?:-\d{1,5})?(?:,\s{0,3}\d{1,4}동\s{0,3}\d{1,5}호)?")),
]
# 2026-11-03은 계좌번호 모양이지만 날짜다. 실제 월·일만 날짜로 본다
_DATE = re.compile(r"(?:19|20)\d{2}-(?:0?[1-9]|1[0-2])-(?:0?[1-9]|[12]\d|3[01])")


def find_pii(text: str) -> list[str]:
    """형식 있는 개인정보 값의 종류를 찾은 순서대로 돌려준다(같은 종류가 여러 번이면 여러 번).
    찾은 값은 지우고 다음 패턴을 봐서, 주민번호 하나가 계좌번호로 한 번 더 세지지 않는다."""
    found = []
    for kind, pattern in PATTERNS:
        for m in pattern.finditer(text):
            if kind == "계좌번호" and _DATE.fullmatch(m.group()):
                continue
            found.append(kind)
            text = text.replace(m.group(), " ")
    return found
